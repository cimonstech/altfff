export type CountryValue =
  | (typeof AFRICAN_COUNTRIES)[number]
  | (typeof REST_OF_WORLD_COUNTRIES)[number]
  | typeof COUNTRY_OTHER_VALUE;

export const COUNTRY_SELECTABLE_VALUES = [
  ...AFRICAN_COUNTRIES,
  ...REST_OF_WORLD_COUNTRIES,
  COUNTRY_OTHER_VALUE,
] as unknown as readonly [CountryValue, ...CountryValue[]];

export const COUNTRY_OPTIONS: { value: string; text: string; disabled?: boolean }[] = [
  ...AFRICAN_COUNTRIES.map((name) => ({ value: name, text: name })),
  { value: COUNTRY_DIVIDER_VALUE, text: "──────────", disabled: true },
  ...REST_OF_WORLD_COUNTRIES.map((name) => ({ value: name, text: name })),
  { value: COUNTRY_OTHER_VALUE, text: COUNTRY_OTHER_VALUE },
];

export function resolveCountryValue(
  value: string | undefined,
  other: string | undefined,
): string | null {
  if (!value) return null;
  if (value === COUNTRY_OTHER_VALUE) {
    const trimmed = other?.trim();
    return trimmed ? `Other: ${trimmed}` : null;
  }
  return value;
}
